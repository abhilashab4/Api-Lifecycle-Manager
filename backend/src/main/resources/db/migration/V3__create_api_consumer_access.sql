CREATE TABLE api_consumer_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL,
    api_name VARCHAR(100) NOT NULL,
    api_version VARCHAR(30) NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_consumer_access_consumer
        FOREIGN KEY (consumer_id)
        REFERENCES api_consumers(id),

    CONSTRAINT uk_consumer_api_version
        UNIQUE (consumer_id, api_name, api_version)
);